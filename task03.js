
// Task 03: Student Grade Calculator

let studentName = "Ammu";
let marks = 85;

console.log("Student Name:", studentName);
console.log("Marks:", marks);

if (marks >= 90) {
    console.log("Grade: A+");
} 
else if (marks >= 80) {
    console.log("Grade: A");
} 
else if (marks >= 70) {
    console.log("Grade: B");
} 
else if (marks >= 60) {
    console.log("Grade: C");
} 
else if (marks >= 50) {
    console.log("Grade: D");
} 
else if (marks >= 35) {
    console.log("Grade: E");
} 
else {
    console.log("Result: Fail");
}

